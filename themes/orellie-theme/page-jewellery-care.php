          <p class="lead">Handcrafted polymer clay earrings are celebrated across New Zealand for their striking sculptural beauty and impossibly featherlight weight. Unlike delicate fine metals or brittle ceramics, high-grade cured polymer clay possesses unique physical properties that make it durable, flexible, and comfortable for daily wear.</p>

          <p>With just a few simple habits, your Orellie handcrafted earrings will stay vibrant, clean, and structurally sound for a lifetime. Here is your definitive guide to caring for, cleaning, storing, and sanitizing polymer clay jewellery in New Zealand.</p>

          <hr>

          <h2>1. Can Polymer Clay Earrings Get Wet?</h2>
          <p>One of the most frequent questions we receive from Kiwi jewelry lovers is whether polymer clay can handle water, humidity, and coastal weather.</p>
          <p><strong>The short answer:</strong> Fully cured artist polymer clay is naturally water-resistant and non-porous. Getting caught in a sudden New Zealand rain shower or gently rinsing dust away with tap water will not harm the clay itself.</p>
          <p><strong>However, we strongly recommend removing your earrings before showering, swimming, or soaking in hot pools:</strong></p>
          <ul>
            <li><strong>Hot Water &amp; Steam:</strong> Prolonged exposure to high heat and steam (such as hot showers, saunas, and thermal pools) can gradually soften adhesives used to secure surgical steel posts and loosen jump ring connections.</li>
            <li><strong>Chlorine &amp; Salt Water:</strong> Pool chemicals and concentrated ocean salt can cause microscopic pitting and tarnish on metallic jump rings, charms, or gold leaf accents over time.</li>
            <li><strong>Shampoos &amp; Body Washes:</strong> Soaps and styling cleansers can leave a dull filmy residue on matte clay surfaces.</li>
          </ul>

          <hr>

          <h2>2. How to Clean Makeup, Foundation &amp; Daily Dust</h2>
          <p>Because earrings sit directly beside cheeks and hair, it is natural for foundation, bronzer, or sunscreen to transfer onto the surface of your earrings. Fortunately, cleaning polymer clay is simple:</p>

          <h3>Routine Everyday Cleaning:</h3>
          <p>After wearing your earrings, gently wipe the clay surface with a clean, dry, lint-free microfiber cloth to remove skin oils and everyday dust.</p>

          <h3>Removing Makeup &amp; Stubborn Marks:</h3>
          <ol>
            <li><strong>Damp Microfiber Cloth:</strong> Lightly dampen a soft cloth with lukewarm water and a drop of mild dishwashing liquid. Gently buff the surface of the clay in small circles.</li>
            <li><strong>Gentle Micellar Water:</strong> For stubborn waterproof foundation or mineral sunscreen, dip a cotton bud in oil-free micellar water and dab gently over the mark. Wipe clean immediately with a damp water-only cloth.</li>
            <li><strong>Allow to Air Dry:</strong> Pat the earrings dry with a soft towel and let them air-dry completely before placing them back in your jewellery box.</li>
          </ol>

          <h3>What to Strictly Avoid:</h3>
          <ul>
            <li><strong>Never use Acetone or Nail Polish Remover:</strong> Acetone is a chemical solvent that dissolves cured polymer clay, melting the surface and destroying any hand-painted details.</li>
            <li><strong>Avoid Abrasive Cleaners &amp; Scrub Brushes:</strong> Harsh scouring pads or gritty polishes will scratch the velvety matte surface finish.</li>
            <li><strong>Avoid Rubbing Alcohol Directly on Clay:</strong> While alcohol is ideal for sanitizing metal posts, do not soak the clay slab in alcohol, especially if it features gold leaf, varnish, or metallic pigments.</li>
          </ul>

          <hr>

          <h2>3. Are Polymer Clay Earrings Durable or Fragile?</h2>
          <p>Many people unfamiliar with artisanal clay worry that polymer clay earrings will shatter like pottery or porcelain if dropped. In reality, properly conditioned and cured polymer clay is remarkably resilient:</p>
          <ul>
            <li><strong>Slight Micro-Flexibility:</strong> High-grade cured clay retains a slight elasticity. If your earrings accidentally slip from your fingers onto hardwood floors or carpet, they will not crack or shatter.</li>
            <li><strong>Avoid Intentional Bending:</strong> While polymer clay has slight give, you should never bend, twist, or apply crushing force to your earrings. Deliberately snapping thin sculptural curves will fracture the piece.</li>
            <li><strong>Treat Sculptural Details with Care:</strong> Delicate handcrafted botanicals, floral petals, and multi-tier dangles should be handled gently by the post when inserting and removing from your ears.</li>
          </ul>

          <hr>

          <h2>4. Sanitizing 316L Surgical Steel Posts Safely</h2>
          <p>Orellie mounts every single pair of earrings on certified <strong>316L medical-grade surgical stainless steel</strong>, ensuring complete biocompatibility for sensitive skin. To keep your piercings hygienic and healthy:</p>
          <ul>
            <li><strong>Target the Metal Posts Only:</strong> Dip a cotton swab or pad into 70% isopropyl alcohol and wipe only the surgical steel post and the butterfly scroll.</li>
            <li><strong>Prevent Alcohol Contact with Clay:</strong> Keep the alcohol-dampened swab focused strictly on the metal hardware to protect the clay finish and post adhesive bond.</li>
            <li><strong>Dry Thoroughly:</strong> Allow the posts to dry completely for 30 seconds before wearing.</li>
            <li><strong>Learn More:</strong> For in-depth metallurgical guidance, visit our <a href="<?php echo esc_url( home_url( '/hypoallergenic-earrings-guide/' ) ); ?>">Hypoallergenic Earrings Guide</a>.</li>
          </ul>

          <hr>

          <h2>5. Safe Storage in New Zealand Coastal Climates</h2>
          <p>New Zealand's coastal humidity, sea breezes, and fluctuating seasonal dampness can affect jewellery if stored improperly. Protect your pieces with these best practices:</p>
          <ul>
            <li><strong>Keep Out of Bathrooms:</strong> High humidity and steam from daily showers create the worst environment for jewellery. Store your collection in a dry bedroom, closet, or dressing area.</li>
            <li><strong>Store in Individual Compartments:</strong> Store pairs separately in a compartmentalized jewellery tray, hanging rack, or within their original rigid Orellie presentation box. This prevents metal posts from scratching clay surfaces.</li>
            <li><strong>Keep Away from Direct Sunlight &amp; Car Dashboards:</strong> UV exposure over many years can fade rich pigments, and extreme heat inside cars can soften post bonds. Keep earrings in cool, shaded spaces.</li>
            <li><strong>Travelling with Earrings:</strong> When packing for weekend getaways across Aotearoa, keep earrings in their sturdy gift box rather than loose inside a toiletry bag.</li>
          </ul>

          <hr>

          <h2>6. The 'Last On, First Off' Golden Rule</h2>
          <p>The single most effective habit for keeping any handmade jewellery pristine is the golden rule of accessorizing:</p>
          <blockquote>
            <strong>Earrings should be the last thing you put on in the morning, and the first thing you take off at night.</strong>
          </blockquote>
          <p>Always apply perfumes, body lotions, hairsprays, styling mousse, and cosmetics <em>before</em> putting on your earrings. The aerosol propellants and chemical solvents in hairspray and perfume can create cloudy film on jewellery surfaces.</p>

