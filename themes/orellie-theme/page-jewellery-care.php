            <div class="faq-item" style="margin-bottom: 1.5rem; padding-bottom: 1.5rem; border-bottom: 1px solid var(--border);">
              <h3 style="margin-bottom: 0.5rem; font-size: 1.2rem;">Will polymer clay earrings break if I drop them?</h3>
              <p>Properly cured polymer clay has subtle micro-flexibility and will not shatter like ceramic when dropped on normal household floors. However, they should not be intentionally bent in half or crushed under heavy objects.</p>
            </div>

