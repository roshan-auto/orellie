              <h3 style="margin-bottom: 0.5rem; font-size: 1.2rem;">Does the care differ between resin and polymer clay earrings?</h3>
              <p>The habits on this page suit both: keep them dry, wipe them gently, keep alcohol and solvents off them, and store them apart. If you are not sure which material your pair is, check its product page or <a href="<?php echo esc_url( home_url( '/contact/' ) ); ?>">ask us</a>.</p>
