          <p class="lead">Orellie earrings come in two materials: some are resin and some are polymer clay. Where we know which one a pair is made from, its product page says so. The care habits below suit both.</p>

          <p>A few simple routines keep your handmade earrings clean, bright and in good shape. Here is how to wear, clean, store and look after them in New Zealand.</p>

          <hr>

          <h2>1. Can My Earrings Get Wet?</h2>
          <p>A splash of rain will not hurt them, but we recommend taking your earrings off before showering, swimming, or soaking in hot pools:</p>
          <ul>
            <li><strong>Hot Water &amp; Steam:</strong> Prolonged exposure to high heat and steam (such as hot showers, saunas, and thermal pools) can gradually soften adhesives used to secure surgical steel posts and loosen jump ring connections.</li>
            <li><strong>Chlorine &amp; Salt Water:</strong> Pool chemicals and concentrated ocean salt can cause microscopic pitting and tarnish on metallic jump rings, charms, or gold leaf accents over time.</li>
            <li><strong>Shampoos &amp; Body Washes:</strong> Soaps and styling products can leave a dull film on the surface of your earrings.</li>
          </ul>

          <hr>

          <h2>2. How to Clean Makeup, Foundation &amp; Daily Dust</h2>
          <p>Because earrings sit directly beside cheeks and hair, it is natural for foundation, bronzer, or sunscreen to transfer onto them. Cleaning them is simple:</p>

          <h3>Routine Everyday Cleaning:</h3>
          <p>After wearing your earrings, gently wipe them with a clean, dry, lint-free microfiber cloth to remove skin oils and everyday dust.</p>

          <h3>Removing Makeup &amp; Stubborn Marks:</h3>
          <ol>
            <li><strong>Damp Microfiber Cloth:</strong> Lightly dampen a soft cloth with lukewarm water and a drop of mild dishwashing liquid. Gently wipe the surface in small circles.</li>
            <li><strong>Gentle Micellar Water:</strong> For stubborn waterproof foundation or mineral sunscreen, dip a cotton bud in oil-free micellar water and dab gently over the mark. Wipe clean immediately with a damp water-only cloth.</li>
            <li><strong>Allow to Air Dry:</strong> Pat the earrings dry with a soft towel and let them air-dry completely before placing them back in your jewellery box.</li>
          </ol>

          <h3>What to Avoid:</h3>
          <ul>
            <li><strong>Acetone or Nail Polish Remover:</strong> Keep solvents well away from your earrings, as they can damage the surface and any hand-painted details.</li>
            <li><strong>Abrasive Cleaners &amp; Scrub Brushes:</strong> Harsh scouring pads or gritty polishes can scratch the finish.</li>
            <li><strong>Rubbing Alcohol on the Earring Itself:</strong> Alcohol is for the metal posts only. Keep it off the body of the earring, especially if it has gold leaf, varnish, or metallic pigments.</li>
          </ul>

          <hr>

          <h2>3. Handling Your Earrings</h2>
          <p>Handmade earrings are made to be worn, and a little gentleness helps them last:</p>
          <ul>
            <li><strong>Avoid Bending:</strong> Never bend, twist, or press hard on your earrings. Thin shapes and fine details can break under force.</li>
            <li><strong>Hold by the Post:</strong> Delicate petals, sculpted details and multi-tier dangles are best handled by the post when you put them in and take them out.</li>
          </ul>

          <hr>

          <h2>4. Sanitizing 316L Surgical Steel Posts Safely</h2>
          <p>Every Orellie pair is made with <strong>316L surgical steel posts</strong>, chosen for sensitive ears. To keep your piercings clean and healthy:</p>
          <ul>
            <li><strong>Target the Metal Posts Only:</strong> Dip a cotton swab or pad into 70% isopropyl alcohol and wipe only the surgical steel post and the butterfly scroll.</li>
            <li><strong>Keep Alcohol Off the Earring:</strong> Keep the alcohol-dampened swab on the metal hardware to protect the finish and the bond that holds the post.</li>
            <li><strong>Dry Thoroughly:</strong> Allow the posts to dry completely for 30 seconds before wearing.</li>
            <li><strong>Learn More:</strong> For more on post metals and sensitive ears, visit our <a href="<?php echo esc_url( home_url( '/hypoallergenic-earrings-guide/' ) ); ?>">Hypoallergenic Earrings Guide</a>.</li>
          </ul>

          <hr>

          <h2>5. Safe Storage in New Zealand Coastal Climates</h2>
          <p>New Zealand's coastal humidity, sea breezes, and fluctuating seasonal dampness can affect jewellery if stored improperly. Protect your pieces with these best practices:</p>
          <ul>
            <li><strong>Keep Out of Bathrooms:</strong> High humidity and steam from daily showers create the worst environment for jewellery. Store your collection in a dry bedroom, closet, or dressing area.</li>
            <li><strong>Store in Individual Compartments:</strong> Store pairs separately in a compartmentalized jewellery tray, hanging rack, or within their original rigid Orellie presentation box. This stops metal posts scratching other earrings.</li>
            <li><strong>Keep Away from Direct Sunlight &amp; Car Dashboards:</strong> UV exposure over many years can fade rich pigments, and extreme heat inside cars can soften post bonds. Keep earrings in cool, shaded spaces.</li>
            <li><strong>Travelling with Earrings:</strong> When packing for weekend getaways across Aotearoa, keep earrings in their sturdy gift box rather than loose inside a toiletry bag.</li>
          </ul>

          <hr>

          <h2>6. The 'Last On, First Off' Golden Rule</h2>
          <p>The single most effective habit for keeping any handmade jewellery pristine is the golden rule of accessorizing:</p>
          <blockquote>
            <strong>Earrings should be the last thing you put on in the morning, and the first thing you take off at night.</strong>
          </blockquote>
          <p>Always apply perfumes, body lotions, hairsprays, styling mousse, and cosmetics <em>before</em> putting on your earrings. The aerosol propellants and chemical solvents in hairspray and perfume can create cloudy film on jewellery surfaces.</p>

